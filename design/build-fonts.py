#!/usr/bin/env python3
"""
Builds the small icon font the site ships (src/assets/fonts/ionicons.woff2) and src/styles/icons.css from design/fonts/Ionicons.ttf.
The text font comes from @fontsource-variable/plus-jakarta-sans, so only icons are built here.
Needs fonttools and brotli (pip install fonttools brotli). Add an icon name to ICONS, run this, and use <i class="i i-NAME"></i>.
"""
import json, sys
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
GLYPHS = Path(sys.argv[1]) if len(sys.argv) > 1 else None  # Ionicons.json from @expo/vector-icons
ICONS = ['flame', 'barbell', 'sparkles', 'people', 'film', 'watch', 'analytics', 'stats-chart', 'trophy', 'flag', 'checkmark-circle',
         'checkmark', 'play', 'person-add', 'gift', 'body', 'camera', 'shirt', 'logo-apple', 'logo-google-playstore', 'cloud-upload',
         'notifications', 'heart', 'chevron-forward', 'flash', 'calendar', 'medal', 'layers', 'ribbon', 'time', 'add', 'pulse',
         'phone-portrait', 'link', 'swap-horizontal', 'calculator', 'timer', 'chatbubble', 'lock-closed', 'moon', 'snow', 'color-palette',
         'mail', 'arrow-forward', 'star', 'trending-up', 'flask', 'videocam', 'apps', 'infinite', 'help-circle', 'close', 'chevron-down',
         'rocket', 'scan', 'qr-code', 'bulb', 'paper-plane', 'sunny', 'cellular', 'battery-full', 'wifi', 'fitness', 'headset', 'musical-notes', 'megaphone', 'download', 'hand-left', 'document-text', 'albums', 'create', 'battery-charging', 'sync-outline', 'send', 'chatbubbles', 'ribbon', 'chevron-up', 'checkmark-done', 'information-circle', 'mail-outline']

def build(src, dst, unicodes=None, text=None):
    opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = ['*']; opts.name_IDs = ['*']; opts.notdef_outline = True
    font = TTFont(src)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=unicodes or [], text=text or '')
    sub.subset(font)
    font.flavor = 'woff2'
    font.save(dst)
    print(dst.name, dst.stat().st_size // 1024, 'KB')

(ROOT / 'src/assets/fonts').mkdir(parents=True, exist_ok=True)
if GLYPHS:
    glyphs = json.loads(GLYPHS.read_text())
    missing = [n for n in ICONS if n not in glyphs]
    if missing: sys.exit(f'unknown icons: {missing}')
    build(ROOT / 'design/fonts/Ionicons.ttf', ROOT / 'src/assets/fonts/ionicons.woff2', unicodes=[glyphs[n] for n in ICONS])
    css = ['/* Generated by design/build-fonts.py. */', "@font-face{font-family:'Ionicons';src:url(../assets/fonts/ionicons.woff2) format('woff2');font-display:block}",
           ".i{font-family:'Ionicons';font-style:normal;font-weight:400;line-height:1;display:inline-block;-webkit-font-smoothing:antialiased}"]
    css += [f".i-{n}::before{{content:'\\{glyphs[n]:x}'}}" for n in ICONS]
    (ROOT / 'src/styles/icons.css').write_text('\n'.join(css) + '\n')
    print('icons.css', len(ICONS), 'icons')
